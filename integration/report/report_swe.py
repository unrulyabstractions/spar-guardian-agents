"""Emit the table of Lucy's-plan pilots for the design document from the run directories.

    python -m integration.report.report_swe [--runs runs] [--out docs/generated/swe_results.tex] runs/swe_* ...

One macro, \\swerows: one row per completed SWE run (runs a provider or harness failure ended are left out) (arm, agents, model steps, minutes, judged cheated,
seeking / obtained / used, posts and posts about the fix, disclosed, rungs, team and agent rewards,
prompt tokens with the cached share, output tokens). Every number comes from run.json,
episodes.jsonl, judge.jsonl and swe_summary.json; none is typed by hand.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if __package__ in (None, ""):
    import sys
    sys.path.insert(0, str(ROOT))

from integration.report.swe_summary import summarize  # noqa: E402

ARM_LABEL = {"none": "standard", "rule": "rule", "wholly_own": "wholly own"}


def tex(s) -> str:
    return (str(s).replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("#", "\\#")
            .replace("%", "\\%").replace("&", "\\&"))


def mtok(n: int) -> str:
    return f"{n / 1e6:.1f}"


def row(run_dir: Path) -> str:
    s = summarize(run_dir)
    run = json.loads((run_dir / "run.json").read_text())
    eps = [json.loads(ln) for ln in (run_dir / "episodes.jsonl").read_text().splitlines() if ln.strip()]
    ag = s["agents"]
    k = lambda f: sum(1 for x in ag.values() if x.get(f))  # noqa: E731
    arm = (f"{'lone' if s['n_agents'] == 1 else str(s['n_agents']) + ' agents'}"
           f"{', jigsaw' if s['jigsaw'] else ''}, {ARM_LABEL.get(s['rule'], s['rule'])}")
    steps = sum(e.get("n_turns") or 0 for e in eps)
    minutes = max((e.get("wall_time") or 0) for e in eps) / 60
    rungs = ", ".join(str(x.get("rung")) for _, x in sorted(ag.items()))
    rewards = ", ".join("--" if x.get("reward") is None else str(x["reward"]) for _, x in sorted(ag.items()))
    team = "--" if s["team_reward"] is None else str(s["team_reward"])
    cached = s["cache_read"] / s["prompt_tokens"] if s["prompt_tokens"] else 0
    return (f"{tex(run_dir.name)} & {tex(arm)} & {steps} & {minutes:.0f} & {s['cheated']}/{s['judged']} & "
            f"{k('reference_solution_seeking')}/{k('reference_solution_obtained')}/{k('reference_solution_used')} & "
            f"{s['board_posts']} ({s['fix_posts']}) & {s['disclosed']} & {tex(rungs)} & {team} & {rewards} & "
            f"{mtok(s['prompt_tokens'])} ({cached:.0%}) & {s['output_tokens'] / 1e3:.0f}k \\\\"
            .replace("%)", "\\%)"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+")
    ap.add_argument("--out", default=str(ROOT / "docs" / "generated" / "swe_results.tex"))
    args = ap.parse_args()
    rows = []
    for r in args.runs:
        eps = [json.loads(ln) for ln in (Path(r) / "episodes.jsonl").read_text().splitlines() if ln.strip()]
        if any(e.get("failure") in ("harness", "connection_closed") for e in eps):
            # a run the provider or harness ended is set aside and never counted (README, Running)
            print(f"set aside, not in the table: {Path(r).name} ({sorted({e.get('failure') for e in eps})})")
            continue
        rows.append(row(Path(r)))
    text = "% generated by integration/report/report_swe.py\n\\newcommand{\\swerows}{%\n" + "\n".join(rows) + "}\n"
    Path(args.out).write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
